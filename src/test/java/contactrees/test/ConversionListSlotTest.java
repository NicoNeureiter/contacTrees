package contactrees.test;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotEquals;
import static org.junit.Assert.assertSame;
import static org.junit.Assert.assertTrue;

import java.util.HashSet;
import java.util.Set;

import org.junit.Test;

import contactrees.Block;
import contactrees.Conversion;

/**
 * Tests for Stage 3b: dense conversion slots (Conversion.getSlot() / ConversionList.getBySlot()),
 * the monotonic conversion-id allocator that replaced the random-then-escalate scheme, and
 * BlockSet's dangling-conversion-reference check.
 *
 * @author Nico Neureiter
 */
public class ConversionListSlotTest extends ContactreesTest {

    @Test
    public void testSlotsAreDistinctAndDense() {
        int slot1 = conv1.getSlot();
        int slot2 = conv2.getSlot();
        assertTrue(slot1 >= 0);
        assertTrue(slot2 >= 0);
        assertNotEquals(slot1, slot2);
        assertSame(conv1, acg.getConversions().getBySlot(slot1));
        assertSame(conv2, acg.getConversions().getBySlot(slot2));
    }

    /**
     * ConversionGraph.store()/restore() swap convs/storedConvs, deep-copying every Conversion via
     * copyTo() in the process -- so the objects behind conv1/conv2 change identity across a
     * restore. Their slots must not: that stability is what MarginalTree's stable numbering and
     * any future targeted operator would rely on.
     */
    @Test
    public void testSlotStableAcrossStoreRestore() {
        int slot1 = conv1.getSlot();
        int slot2 = conv2.getSlot();

        acg.store();

        Conversion conv3 = new Conversion(node2, node3, 0.5, acg, 0);
        acg.addConversion(conv3);
        int slot3 = conv3.getSlot();
        assertTrue(slot3 >= 0);
        assertNotEquals(slot1, slot3);
        assertNotEquals(slot2, slot3);

        acg.restore();

        // conv3 must be gone; conv1/conv2 (different objects post-swap) must keep their slots.
        assertEquals(2, acg.getConvCount());
        Conversion restoredConv1 = acg.getConversions().get(conv1.getID());
        Conversion restoredConv2 = acg.getConversions().get(conv2.getID());
        assertEquals(slot1, restoredConv1.getSlot());
        assertEquals(slot2, restoredConv2.getSlot());
        assertSame(restoredConv1, acg.getConversions().getBySlot(slot1));
        assertSame(restoredConv2, acg.getConversions().getBySlot(slot2));
    }

    @Test
    public void testDuplicateConversionGetsFreshSlot() {
        int originalSlot = conv1.getSlot();
        Conversion dup = acg.addDuplicateConversion(conv1);

        assertNotEquals(originalSlot, dup.getSlot());
        assertNotEquals(conv1.getID(), dup.getID());
        assertSame(conv1, acg.getConversions().getBySlot(originalSlot));
        assertSame(dup, acg.getConversions().getBySlot(dup.getSlot()));
    }

    @Test
    public void testSlotReleasedAndReusedAfterRemove() {
        int slot1 = conv1.getSlot();

        acg.removeConversion(conv1);
        blockSet.removeConversion(conv1);
        assertEquals(-1, conv1.getSlot());

        Conversion conv3 = new Conversion(node2, node3, 0.5, acg, 0);
        acg.addConversion(conv3);
        assertEquals("the just-freed slot should be reused rather than the array growing",
                slot1, conv3.getSlot());
    }

    /**
     * The old getFreeKey() (Randomizer.nextInt(10000), escalating only on a collision against
     * LIVE keys) could, after enough churn, hand out an id that collided with a stale reference
     * still held elsewhere (~1e-4 per add). The monotonic counter must never repeat an id within
     * one run, even across many add/remove cycles and even when some ids are assigned explicitly
     * (Newick parsing, test fixtures) rather than through getFreeKey().
     */
    @Test
    public void testConversionIdsNeverRepeat() {
        Set<Integer> seenIds = new HashSet<>();
        seenIds.add(conv1.getID());
        seenIds.add(conv2.getID());

        for (int i = 0; i < 500; i++) {
            Conversion c = acg.addNewConversion();
            assertTrue("id " + c.getID() + " was already used", seenIds.add(c.getID()));
            acg.removeConversion(c);
        }

        // An explicitly-assigned id (bypassing getFreeKey(), as Newick parsing and test fixtures
        // do) must also push the counter forward, so a later auto-generated id can't collide.
        Conversion explicit = new Conversion(node2, node3, 0.5, acg, 100000);
        acg.addConversion(explicit);
        Conversion autoGenerated = acg.addNewConversion();
        assertNotEquals(explicit.getID(), autoGenerated.getID());
    }

    /**
     * BlockSet.isInvalid() closes a real correctness gap: nothing previously validated that a
     * live Block doesn't reference a conversion id no longer present in the ACG (a stale
     * reference used to be able to silently rebind to an unrelated live conversion once the old
     * random-id scheme collided; now it just resolves to null and must be caught here).
     *
     * Uses acg2/blockSet2/conv2_1, not acg/blockSet/conv1: ContactreesTest.getBlockSet() always
     * overwrites the shared `blockSet` field as a side effect, so after setup() runs
     * buildACG_1() then buildACG_2(), `blockSet` actually ends up wired to acg2, not acg. Every
     * other test gets away with that pre-existing fixture quirk because it only touches bare
     * Block objects (no acg dependency); this is the first test to exercise a BlockSet method
     * that needs the pairing to be real, so it must sidestep the mismatch rather than trip over
     * it.
     */
    @Test
    public void testBlockSetDetectsDanglingConversionReference() {
        assertFalse(blockSet2.isInvalid());

        Block block = blockSet2.getBlocks().get(0);
        block.addMove(conv2_1);
        assertFalse(blockSet2.isInvalid());

        // Remove the conversion from the ACG WITHOUT clearing the Block's reference to it --
        // exactly the scenario this check exists to catch.
        acg2.removeConversion(conv2_1);
        assertTrue(blockSet2.isInvalid());
    }
}
